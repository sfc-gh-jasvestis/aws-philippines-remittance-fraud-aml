-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT outlet.ID AS ENTITY_ID, outlet.NAME AS ENTITY_NAME,
       outlet.REGION, outlet.CATEGORY, outlet.DD_TIER, outlet.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.TRANSFER_COUNT) AS TRANSFER_COUNT,
       SUM(observation.VOLUME_PHP) AS VOLUME_PHP,
       SUM(observation.ALERT_COUNT) AS ALERT_COUNT,
       SUM(observation.CONFIRMED_COUNT) AS CONFIRMED_COUNT,
       SUM(observation.STR_FILED) AS STR_COUNT,
       SUM(observation.REVIEW_DUE) AS REVIEW_DUE,
       SUM(observation.REVIEW_COMPLETED) AS REVIEW_COMPLETED,
       100.0 * SUM(observation.CONFIRMED_COUNT) / NULLIF(SUM(observation.ALERT_COUNT), 0) AS ALERT_PRECISION_PCT,
       100.0 * SUM(observation.REVIEW_COMPLETED) / NULLIF(SUM(observation.REVIEW_DUE), 0) AS REVIEW_COMPLIANCE_PCT,
       AVG(observation.SPLIT_TXN_PCT) AS AVG_SPLIT_TXN_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.OUTLET_DAILY observation
JOIN RAW.OUTLETS outlet ON outlet.ID = observation.ENTITY_ID
GROUP BY outlet.ID, outlet.NAME, outlet.REGION, outlet.CATEGORY, outlet.DD_TIER, outlet.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(TRANSFER_COUNT) AS TRANSFER_COUNT, SUM(VOLUME_PHP) AS VOLUME_PHP,
       SUM(ALERT_COUNT) AS ALERT_COUNT, SUM(CONFIRMED_COUNT) AS CONFIRMED_COUNT,
       100.0 * SUM(CONFIRMED_COUNT) / NULLIF(SUM(ALERT_COUNT), 0) AS ALERT_PRECISION_PCT
FROM RAW.OUTLET_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.RULE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT DETECTION_RULE, SUM(ALERT_COUNT) AS ALERT_COUNT,
       SUM(CONFIRMED_COUNT) AS CONFIRMED_COUNT,
       SUM(STR_FILED) AS STR_COUNT,
       SUM(VOLUME_PHP) AS FLAGGED_VOLUME_PHP,
       100.0 * SUM(CONFIRMED_COUNT) / NULLIF(SUM(ALERT_COUNT), 0) AS ALERT_PRECISION_PCT
FROM RAW.OUTLET_DAILY
WHERE ALERT_COUNT > 0
GROUP BY DETECTION_RULE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(ALERT_COUNT) AS ALERTS, SUM(CONFIRMED_COUNT) AS CONFIRMED,
         SUM(STR_FILED) AS STRS, SUM(VOLUME_PHP) AS VOLUME,
         SUM(REVIEW_DUE) AS REVIEW_DUE, SUM(REVIEW_COMPLETED) AS REVIEW_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.OUTLET_DAILY
), book AS (SELECT COUNT(*) AS OUTLET_COUNT FROM RAW.OUTLETS),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.AGENT_DOCUMENTS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Alert Precision' AS TITLE,
         100.0 * CONFIRMED / NULLIF(ALERTS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Alerts Raised', ALERTS, '' FROM observations
  UNION ALL SELECT 3, 'Confirmed Suspicious', CONFIRMED, '' FROM observations
  UNION ALL SELECT 4, 'STRs Filed', STRS, '' FROM observations
  UNION ALL SELECT 5, 'Transfer Volume (PHP M)', VOLUME / 1e6, '' FROM observations
  UNION ALL SELECT 6, 'Outlet Review Compliance', 100.0 * REVIEW_COMPLETED / NULLIF(REVIEW_DUE, 0), '%' FROM observations
  UNION ALL SELECT 7, 'Outlets Monitored', OUTLET_COUNT, '' FROM book
  UNION ALL SELECT 8, 'Agent Document Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 9, 'Agent Documents Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.RULE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
